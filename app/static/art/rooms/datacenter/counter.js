/* Стойка поддержки ЦОДа.
   dcCounterSvg(): светлая стойка с двумя мониторами, клавиатурами, роутером и ключами. Размер совпадает с cafeCounterSvg (общий каркас). */

function dcCounterSvg() {
  const x = 2.05, y = 0.78, w = 3.9, d = 0.92, h = 28;
  const parts = [box(x, y, w, d, h, "#eef3fa", "#51607a", "#3d4a63")];
  for (let i = 1; i < 10; i += 1) parts.push(seg([x + (i * w) / 10, y + d, 4], [x + (i * w) / 10, y + d, h - 3], "rgba(0,0,0,.25)", 1));
  parts.push(seg([x, y + d, h], [x + w, y + d, h], "#7ff5ee", 1.4));
  parts.push(face([[x, y + d + 0.01, 0], [x + w, y + d + 0.01, 0], [x + w, y + d + 0.01, 3], [x, y + d + 0.01, 3]], "#2f3a4f"));
  // два монитора с терминалами и клавиатуры
  [[2.55, "#222b3d"], [4.3, "#222b3d"]].forEach(([mx, tone]) => {
    parts.push(box(mx, 0.95, 0.9, 0.08, 15, "#44506a", "#34405a", "#2a3550", h + 3));
    parts.push(face([[mx + 0.06, 1.04, h + 6], [mx + 0.84, 1.04, h + 6], [mx + 0.84, 1.04, h + 16], [mx + 0.06, 1.04, h + 16]], tone));
    for (let k = 0; k < 4; k += 1) parts.push(seg([mx + 0.12, 1.05, h + 8 + k * 2.2], [mx + 0.3 + (k * 0.17) % 0.5, 1.05, h + 8 + k * 2.2], k % 2 ? "#8ff59a" : "#5ff2ea", 1));
    parts.push(box(mx + 0.18, 1.2, 0.55, 0.22, 1.2, "#b4c2d6", "#44506a", "#34405a", h));
  });
  // роутер с антеннами и стойка с «ключами»
  parts.push(box(5.3, 1.08, 0.5, 0.36, 3, "#34405a", "#2a3550", "#222b3d", h));
  parts.push(seg([5.38, 1.12, h + 3], [5.33, 1.12, h + 14], "#34405a", 1.2));
  parts.push(seg([5.7, 1.12, h + 3], [5.75, 1.12, h + 14], "#34405a", 1.2));
  parts.push(face([[5.36, 1.45, h + 1], [5.46, 1.45, h + 1], [5.46, 1.45, h + 2.4], [5.36, 1.45, h + 2.4]], "#8ff59a"));
  parts.push(box(3.55, 1.35, 0.3, 0.2, 7, "#fff7d6", "#e8d8a4", "#c9b985", h));
  return parts.join("");
}
