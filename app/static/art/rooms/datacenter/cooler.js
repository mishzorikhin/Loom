/* Шкаф охлаждения.
   dcCoolerSvg(x, y): светлый шкаф 0.5 x 0.5 x 26 с решёткой; стоит вместо растений. */

function dcCoolerSvg(x, y) {
  return box(x, y, 0.5, 0.5, 26, "#eef3fa", "#aab7cc", "#667390")
    + face([[x + 0.08, y + 0.51, 6], [x + 0.42, y + 0.51, 6], [x + 0.42, y + 0.51, 22], [x + 0.08, y + 0.51, 22]], "#51607a")
    + [0, 1, 2, 3].map((i) => seg([x + 0.1, y + 0.52, 8 + i * 4], [x + 0.4, y + 0.52, 8 + i * 4], "#cdd7e6", 0.9)).join("");
}
