/* Окно ЦОДа.
   dcWindowSvg(): окно на машинный зал: шесть стоек со светодиодами DC_LED (PAL.neon), блик, подоконник. */

/* Окно на задней стене: за стеклом ряды стоек. Небо через окно не видно, только машинный зал. */
function dcWindowSvg() {
  const x0 = 2.25;
  const x1 = 5.75;
  const y = 0.03;
  const parts = [
    face([[x0 - 0.12, y, 28], [x1 + 0.12, y, 28], [x1 + 0.12, y, 80], [x0 - 0.12, y, 80]], "#3a4660"),
    face([[x0, y + 0.02, 33], [x1, y + 0.02, 33], [x1, y + 0.02, 76], [x0, y + 0.02, 76]], "#222b3d"),
  ];
  for (let i = 0; i < 6; i += 1) {
    const a = x0 + 0.12 + i * 0.57;
    parts.push(face([[a, y + 0.03, 34], [a + 0.42, y + 0.03, 34], [a + 0.42, y + 0.03, 70], [a, y + 0.03, 70]], "#33405a"));
    for (let k = 0; k < 7; k += 1) {
      parts.push(face([[a + 0.06, y + 0.04, 37 + k * 4.6], [a + 0.36, y + 0.04, 37 + k * 4.6], [a + 0.36, y + 0.04, 39 + k * 4.6], [a + 0.06, y + 0.04, 39 + k * 4.6]],
        DC_LED[(i + k * 3) % DC_LED.length], 0.9));
    }
  }
  parts.push(face([[x0, y + 0.05, 33], [x1, y + 0.05, 33], [x1, y + 0.05, 46], [x0, y + 0.05, 46]], "#ffffff", 0.1));
  parts.push(box(x0 - 0.2, 0.02, x1 - x0 + 0.4, 0.2, 3, "#9aa8c0", "#7d8aa3", "#667390", 25));
  return parts.join("");
}
