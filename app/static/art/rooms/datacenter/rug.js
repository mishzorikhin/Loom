/* Коврик ЦОДа.
   dcRugSvg(): антистатический коврик со жёлто-чёрной разметкой у стойки поддержки. */

/* Жёлто-чёрная разметка у стойки поддержки и антистатический коврик. */
function dcRugSvg() {
  const x0 = 2.4, x1 = 5.9, y0 = 1.95, y1 = 3.2;
  const parts = [
    face([[x0, y0, 0.2], [x1, y0, 0.2], [x1, y1, 0.2], [x0, y1, 0.2]], "#3a4660"),
    face([[x0 + 0.15, y0 + 0.15, 0.3], [x1 - 0.15, y0 + 0.15, 0.3], [x1 - 0.15, y1 - 0.15, 0.3], [x0 + 0.15, y1 - 0.15, 0.3]], "#4a5873"),
  ];
  for (let i = 0; i < 14; i += 1) {
    const a = x0 + i * ((x1 - x0) / 14);
    const b = a + (x1 - x0) / 28;
    parts.push(face([[a, y1 - 0.12, 0.4], [b, y1 - 0.12, 0.4], [b + 0.1, y1, 0.4], [a + 0.1, y1, 0.4]], i % 2 ? "#ffd25a" : "#34405a"));
  }
  return parts.join("");
}
