VENUES = {"cafe": CAFE, "datacenter": DATACENTER}


def venue_of(kind: str | None) -> Venue:
    return VENUES.get(kind or "", CAFE)


def day_curve(minute: float, table: tuple) -> float:
    weight = table[0][1]
    for start, value in table:
        if minute / 60 >= start:
            weight = value
    return weight


