"""Типы заведений: чем «кофейня» отличается от «ЦОДа» для движка.

Каркас один: каталог, персонал, гости, визиты, деньги, диалоги (см. `docs/model.md`, «Замысел заведений»). Тип задаёт
слова в промптах, характеры и бюджеты гостей, поток приходов и стартовые данные. Правила потока, вердикты и границы
правок остаются общими в `rules.py`.
"""

from dataclasses import dataclass, field


@dataclass(frozen=True)
class Venue:
    kind: str
    prompts: str                      # подкаталог app/prompts с описаниями ролей этого типа; пусто — общие
    where: str                        # «в кофейне»
    this_place: str                   # «в этой кофейне»: так знакомый советует место
    spot: str                         # «у стойки»
    staff_word: str                   # «бариста»
    staff_of: str                     # «бариста» в родительном: «выглядела так» не нужно, нужны только слова
    staff_acc: str                    # «бариста» в творительном: «с баристой»
    staff_dat: str                    # «бариста» в дательном: «скажи бариста»
    staff_look: str                   # как описан работник в вердикте гостя ({name}, {mood})
    item_word: str                    # «меню» / «прайс»
    served_phrase: str                # «Тебе подали»
    leave_phrase: str                 # «Ты вышел на улицу.»
    queue_phrase: str                 # «Бариста занят другим гостем.»
    traits: tuple
    trait_say: dict
    budgets: tuple
    voices: dict
    names: tuple
    base_per_hour: float              # гостей в час при популярности 1 и среднем часе
    max_visits: int
    day_curve: tuple                  # ((час, вес), …)
    price_max: int
    stay: bool                        # сидит ли гость после заказа (кофейня) или уходит сразу (ЦОД)
    role_words: dict = field(default_factory=dict)  # подписи ролей для критика и страницы


